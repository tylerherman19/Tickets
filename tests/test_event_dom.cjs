 assert.equal(requests.filter(r=>r.name==='tix_event_listings').at(-1).body.p_qty,4);
 d.querySelector('#history-basis').value='fees_included_tax_reported';d.querySelector('#history-basis').dispatchEvent(new w.Event('change'));
